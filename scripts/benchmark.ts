import { readFileSync, writeFileSync } from 'node:fs';
import { buildGraph, planRoutes } from '../packages/core/src/routing';
import type { FaresData } from '../packages/core/src/fares';
import type { MetroData } from '../packages/core/src/types';

const metro = JSON.parse(readFileSync('data/metro.json', 'utf8')) as MetroData;
const fares = JSON.parse(readFileSync('data/curated/fares.json', 'utf8')) as FaresData;
const { trips } = JSON.parse(readFileSync('data/benchmark/trips.json', 'utf8')) as {
  trips: [string, string][];
};
const graph = buildGraph(metro);
const name = (id: string) => metro.stations.find((s) => s.id === id)?.name.en ?? `?${id}`;

const rows: string[] = [];
let n = 0;
for (const [from, to] of trips) {
  n++;
  const routes = planRoutes(graph, from, to, { fares });
  if (!routes.length) {
    rows.push(`| ${n} | ${name(from)} → ${name(to)} | NO ROUTE | | | | | | | |`);
    continue;
  }
  for (const r of routes) {
    const via = r.transfers.map((t) => name(t.stationId)).join(', ') || '-';
    const label = r.mode === 'fastest' ? 'fastest' : 'fewest transfers';
    rows.push(
      `| ${n} | ${name(from)} → ${name(to)} | ${label} | ${r.stops} | ${via} | ${Math.round(r.totalSec / 60)} | ${r.fare ?? '-'} | | | |`,
    );
  }
}

const md = `# Benchmark: our planner vs the Egypt Transport app

Generated by \`npm run benchmark\` from \`data/benchmark/trips.json\`. Fill the App columns by entering the same
trips in the Egypt Transport app as a normal user (black-box only; never decompile it or copy its data).
Note which counting rule the app uses for fares (boarding station counted, interchange once).

| # | Trip | Our option | Our stops | Our transfers | Our min | Our fare (EGP) | App stops | App min / fare | Notes |
|---|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}
`;
writeFileSync('docs/benchmark.md', md);
console.log(`Wrote docs/benchmark.md (${trips.length} trips)`);
